/** Активные сферы для возраста (какие вкладки/строки вообще показывать). */
export function activeDomains(ageM: number): Domain[] {
  const present = new Set(CARDS.filter((c) => ageM >= c.minM && ageM <= c.maxM).map((c) => c.domain));
  return ORDER.filter((d) => present.has(d));
}

/** По одной самой релевантной карточке на сферу для текущего возраста. */
export function digestFor(ageM: number, weekSeed = 0): DigestCard[] {
  const out: DigestCard[] = [];
  for (const d of activeDomains(ageM)) {
    const pool = CARDS.filter((c) => c.domain === d && ageM >= c.minM && ageM <= c.maxM);
    if (!pool.length) continue;
    // если карточек в диапазоне несколько — чередуем по неделям
    out.push(pool[weekSeed % pool.length]);
  }
  return out;
}
